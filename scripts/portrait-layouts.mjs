// How each original page design (1400 × 990) is laid out on upright A4 (990 × 1400).
// Read by build-portrait-templates.mjs. Each design has `rules`, applied in order; every original
// element must be taken by exactly one rule (unless a rule says `copy`).
//   ids / in / type / shape / orient / where  select elements (`in` tests the element's centre)
//   to: [x, y, w, h]   fits the selection's bounding box into this box (w only: scales as a whole)
//   x / y              piecewise maps [[from, to], …] (one pair is a shift), dx / dy shifts
//   u                  scale of type and of shapes that keep their proportions (icons, circles)
//   line: [x1,y1,x2,y2] redraws a line,   drop: true leaves elements out,   set: {…} overrides
// `repeat` continues rows: elements centred in `band` are copied every `pitch` while they fit
// above `until`. Frames and lines get new geometry in their new size, so nothing is distorted.

import fs from 'node:fs';
const originals = JSON.parse(fs.readFileSync(new URL('../src/lib/reference/page-templates.json', import.meta.url), 'utf8'));
const gridOf = id => originals.find(d => d.id === id).grid;

const X850 = [[70, 70], [1330, 920]];               // content width 70…1330 → 70…920
const box = (ids, to, extra = {}) => ({ ids: [].concat(ids), to, ...extra });
const region = (inRect, extra = {}) => ({ in: inRect, ...extra });
const rest = extra => ({ ...extra });
/** Ruled paper: lines get the portrait width, the last row repeats down the page. */
function ruled(g, { until, right = 990 - g.left } = {}) {
  const lastTop = g.top + (g.count - 1) * g.pitch;
  const op = { band: [0, lastTop - 6, 990, lastTop + g.pitch - 6], pitch: g.pitch, until };
  return {
    rules: [rest({ x: [[g.left, g.left], [g.right, right]] })],
    repeat: [op],
    grid: () => ({ ...g, right, count: g.count + op.made }),
  };
}
