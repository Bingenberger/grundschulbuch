import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {build} from 'esbuild';
import {createRequire} from 'node:module';
const directory=await fs.mkdtemp(path.join(os.tmpdir(),'grundschulbuch-endless-'));
process.env.GRUNDSCHULBUCH_DATA_DIR=directory;
after(()=>fs.rm(directory,{recursive:true,force:true}));
const books=await import('../src/lib/notebooks.mjs');
const compiled=await build({entryPoints:['src/lib/notebook-model.ts'],bundle:true,write:false,platform:'node',format:'cjs'});
const mod={exports:{}};new Function('require','module','exports',compiled.outputFiles[0].text)(createRequire(import.meta.url),mod,mod.exports);
const {newPage,dimensions}=mod.exports;
const field=(y)=>({id:randomUUID(),type:'text',x:20,y,width:100,height:25,rotation:0,locked:false,color:'#123456',font:'Andika',fontSize:18,text:'Weit unten'});
test('Endlospapier wächst mit Inhalten; bestehendes A4 behält seine Maße',()=>{
 const page=newPage('blanko','landscape');assert.deepEqual(dimensions(page),{width:297,height:210});
 page.paperMode='endless';assert.equal(dimensions(page).height,594);
 page.elements=[field(1600)];assert.equal(dimensions(page).height,1800);
 assert.equal(dimensions({...page,paperMode:undefined}).height,210);
});
test('Weit unten geschriebene Texte und Striche bleiben nach dem Speichern erhalten',async()=>{
 const owner=randomUUID(),page={...newPage('blanko','landscape'),paperMode:'endless',elements:[field(1600)]};
 page.elements.push({id:randomUUID(),type:'stroke',x:10,y:1700,width:90,height:10,rotation:0,locked:false,color:'#123456',penWidth:1,opacity:1,points:[{x:10,y:1700,pressure:.5},{x:100,y:1710,pressure:.8}]});
 const created=await books.createBook(owner,'kind',{title:'Endlos',pages:[page]});
 const saved=await books.savePage(owner,created.book.id,{...created.pages[0],elements:created.pages[0].elements.map(e=>({...e,y:e.y+100}))},{features:['text','pen']});
 const opened=await books.getBook(owner,created.book.id);assert.equal(opened.pages[0].paperMode,'endless');assert.equal(opened.pages[0].elements[0].y,1700);assert.equal(opened.pages[0].elements[1].points[1].y,1710);
 await assert.rejects(books.savePage(owner,created.book.id,{...saved,paperMode:undefined},{features:['text','pen']}));
 assert.throws(()=>books.validatePage({...page,paperMode:'unbekannt'}),/Papiermodus/);
 assert.throws(()=>books.validatePage({...page,paperMode:undefined}));
});
