test('Globale Vorgaben, unabhängige Klassen-Ausnahmen und Rückkehr zur Vererbung',async()=>{
  const key='bp-policy-inheritance';
  await books.setTemplatePolicy(key,null,{enabled:false,insertion:'fixed'});
  await books.setTemplatePolicy(key,a.id,{enabled:true});
  let s=await books.readSchoolTemplates();
  assert.deepEqual(templatePolicy(s.policies,s.hidden,key),{enabled:false,insertion:'fixed'});
  assert.deepEqual(templatePolicy(s.policies,s.hidden,key,a.id),{enabled:true,insertion:'fixed'});
  assert.equal(templatePolicy(s.policies,s.hidden,key,b.id).enabled,false);
  await books.setTemplatePolicy(key,a.id,{insertion:'editable'});
  await books.setTemplatePolicy(key,null,{enabled:true,insertion:'template'});
  s=await books.readSchoolTemplates();
  assert.equal(templatePolicy(s.policies,s.hidden,key,a.id).insertion,'editable');
  assert.equal(templatePolicy(s.policies,s.hidden,key,b.id).insertion,'template');
  await books.setTemplatePolicy(key,a.id,{enabled:null,insertion:null});
  s=await books.readSchoolTemplates();assert.equal(s.policies.classes[a.id][key],undefined);
  assert.deepEqual(templatePolicy(s.policies,s.hidden,key,a.id),{enabled:true,insertion:'template'});
});
