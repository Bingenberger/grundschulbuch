test('Einfügearten verändern nur die neue Kopie; vorhandene Seiten werden nicht nachträglich gesperrt',async()=>{
  const p=page('bp-policy-copy');
  assert.equal(applyInsertionMode(p,'template'),p);
  assert.equal(applyInsertionMode(p,'fixed').elements[0].locked,true);assert.equal(p.elements[0].locked,false);
  const book=await books.createBook(owner,'lehrkraft',{title:'Vorher',pages:[p]});
  await books.setTemplatePolicy(p.template,null,{insertion:'fixed'});
  assert.equal((await books.getBook(owner,book.book.id)).pages[0].elements[0].locked,false);
  const newPage=await books.addPage(owner,book.book.id,page(p.template));assert.equal(newPage.page.elements[0].locked,true);
  const empty=await books.addPage(owner,book.book.id,{...page(p.template),elements:[]});
  const authored=await books.savePage(owner,book.book.id,{...empty.page,elements:page(p.template).elements});
  assert.equal(authored.elements[0].locked,false,'Später selbst eingefügte Inhalte sind keine Vorlagenübernahme');
  const changed=await books.savePage(owner,book.book.id,{...book.pages[0],elements:book.pages[0].elements.map(el=>({...el,text:'Geändert'}))});
  assert.equal(changed.elements[0].locked,false);
});
test('Server prüft Freigabe und Einfügeart bei Erstellen, Hinzufügen und erster Übernahme in eine leere Seite',async()=>{
  const key='bp-policy-server',p=page(key);
  await books.setTemplatePolicy(key,null,{enabled:false});
  await assert.rejects(books.createBook(owner,'lehrkraft',{title:'Gesperrt',pages:[p]}),forbidden);
  const book=await books.createBook(owner,'lehrkraft',{title:'Leer'});
  await assert.rejects(books.addPage(owner,book.book.id,p),forbidden);
  await assert.rejects(books.savePage(owner,book.book.id,{...p,id:book.pages[0].id}),forbidden);
  await books.setTemplatePolicy(key,a.id,{enabled:true,insertion:'fixed'});
  const inserted=await books.savePage(owner,book.book.id,{...p,id:book.pages[0].id,templateClassId:a.id});
  assert.equal(inserted.elements[0].locked,true);assert.equal(inserted.templateClassId,a.id);
  await books.setTemplatePolicy(key,b.id,{enabled:true,insertion:'editable'});
  const editable=await books.addPage(owner,book.book.id,{...p,templateClassId:b.id,elements:p.elements.map(el=>({...el,locked:true}))});
  assert.equal(editable.page.elements[0].locked,false);
  await assert.rejects(books.addPage(owner,book.book.id,{...p,templateClassId:foreign.id}),forbidden);
});
